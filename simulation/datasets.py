    def expand_bloon_groups(bloon_text):
        expanded_list = []
        
        # Split by newline to get each bloon group
        bloon_groups = bloon_text.split('\n')
        
        for group in bloon_groups:
            # Extract bloon type and count
            match = re.match(r'(\w+) ×(\d+)', group)
            if match:
                bloon_type = match.group(1)
                count = int(match.group(2))
                
                # Add the bloon type to the list 'count' times
                expanded_list.extend([bloon_type] * count)
        
        return expanded_list

    # Example usage with the DataFrame from the previous code
