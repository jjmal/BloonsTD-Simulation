def sort_positions_by_middle_dist(positions: List[Tuple[int,int]]) -> List[Tuple[int,int]]:
    """
    Sorts a list of positions by their distance to the middle point of the map (ascending).
    :param positions: A list of points (x,y)
    :returns: A list of points (x,y), sorted by their distance 
    """
    pos_dist = {}
    for pos in positions:
        pos_dist[pos] = compute_distance_from_centre(pos)
    return sorted(pos_dist, key = pos_dist.get)

