def compute_distance_from_centre(pos: Tuple[int,int]) -> float:
    """
    Computes the distance from the centre to the point with position pos.
    :param pos: position of the point (x,y)
    :returns: Eucledean distance to point (239.5, 239.5), which is the centre of the map
    """
