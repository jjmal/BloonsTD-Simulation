# Adopted from sklearn's implementation
def min_max_scaling(mn: float, mx: float, vals: List[float]) -> List[float]:
    """
    Applies min-max scaling to a list of values
    """
    val_min = min(vals)
    val_max = max(vals)
    out = []
    for val in vals:
        std = (val - val_min) / (val_max - val_min)
        out.append(std * (mx - mn) + mn)
    return out


def min_max_cosine(mn: float, mx: float, val: float) -> float:
    """
    Applies min-max scaling to a cosine function.
    """
    return val*(mx - mn) + mn

def min_max_distance(mn: float, mx: float, val: float) -> float:
    min_dist_inv = 1/240 # inverse of range of upgraded Super Monkey Tower
    max_dist_inv = 1/30  # inverse of smallest possible distace from Tower (radius 10) to the middle of the track (width 20)

    std = (val - min_dist_inv) / (max_dist_inv - min_dist_inv)
