    """
    Generates all integer points that lie within a square.
    :param center: coordinates of the square's center, (x,y) tuple
    :param width: shortest distance from center to edge (half the side length).
    :param modulo: if both point coordinates are divisible by modulo, it will be kept; approximately
    1/(modulo^2) points will be kept
    """
    center_x, center_y = center
    
    # Calculate the square boundaries
    min_x = center_x - width
    max_x = center_x + width
    min_y = center_y - width
    max_y = center_y + width
    
    # Generate all integer points within the square
    points = []
    for x in range(min_x, max_x + 1):
        for y in range(min_y, max_y + 1):
            # Filter for divisibility
            if is_point_modulo((x,y), modulo):
                points.append((x, y))
    
    return points


