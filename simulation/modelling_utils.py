def is_point_modulo(point: Tuple[int,int], modulo: int) -> bool:
    """
    Checks if both coordinates of a point are divisible by a number.
    :param point: An (x,y) tuple
    :param modulo: number for the divisibility check
    :returns: True if both coordinates are divisible by modulo; False otherwise
    """
    x, y = point
    if (x%modulo == 0 and y%modulo == 0):
        return True
    return False

def filter_point_set_modulo(points: List[Tuple[int,int]], modulo: int) -> List[Tuple[int,int]]:
    """
    Filters a list of points, checking if both coordinates of a point are divisible by a number. Approximately
    1/(modulo^2) points will be kept, assuming a uniformly random distribution.
    :param points: A List of points (x,y) 
    :param modulo: number for the divisibility check
    :returns: A List of points (x,y) such that x, y are both divisible by modulo
    """
    out = []
    for point in points:
        if is_point_modulo(point, modulo):
            out.append(point)
    return out

