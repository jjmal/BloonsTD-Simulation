def square_to_right_triangle(square_points: List[Tuple[int,int]], orientation: str) -> List[Tuple[int,int]]:
    """
    Convert a set of integer points forming a square to a set forming a right triangle.
    The triangle will be half of the square with the square's diagonal as the hypotenuse.
    :param square_points : list of (x, y) integer coordinates that form a square.
    :param orientation: Which half of the square to return as a triangle. Can be 'lower_left',
    'upper_left', 'lower_right', or 'upper_right'.
    :returns: List of (x, y) integer points that form a right triangle.
    """

    # Validate orientation parameter
    valid_orientations = ['lower_left', 'upper_left', 'lower_right', 'upper_right']
    if orientation not in valid_orientations:
        raise ValueError(f"Orientation must be one of {valid_orientations}")
    
    # Find the bounds of the square
    x_coords = [p[0] for p in square_points]
    y_coords = [p[1] for p in square_points]
    
    min_x, max_x = min(x_coords), max(x_coords)
    min_y, max_y = min(y_coords), max(y_coords)
    
    # Select points based on orientation
    triangle_points = []
    
    for x, y in square_points:
        if orientation == 'lower_left':
            # Points below the diagonal from bottom-left to top-right
            if x + y <= max_x + min_y:
                triangle_points.append((x, y))
        elif orientation == 'upper_left':
            # Points above the diagonal from bottom-left to top-right
            if x + y >= max_x + min_y:
                triangle_points.append((x, y))
        elif orientation == 'lower_right':
            # Points below the diagonal from top-left to bottom-right
            if y - x <= min_y - min_x:
                triangle_points.append((x, y))
        elif orientation == 'upper_right':
            # Points above the diagonal from top-left to bottom-right
            if y - x >= min_y - min_x:
                triangle_points.append((x, y))
    
    return triangle_points


